"""Auto-Generate Pipeline Docs from PDFs (pure-logic, secure-by-design).

This module implements the *pure-logic* portion of the "Auto-Generate Pipeline
Docs from PDFs" spec. It does NOT open sockets, read files, import torch, or
call any LLM/network service. Instead it provides:

  * PSN_PDF_Structured_Extractor -- validates a PDF path against an allow-list
    of safe extensions, and (when a pre-extracted text payload is supplied)
    returns structured text blocks plus a JSON metadata string.
  * PSN_LLM_Doc_Generator -- builds a deterministic, well-formed Markdown
    document from the extracted text blocks and reports a heuristic
    confidence score. No LLM is contacted; the "generation" is a local,
    reproducible formatting step.

All functions take plain values (strings, numbers, booleans, JSON text) and
return plain values. No file, OS, network, subprocess, or eval/exec access.
"""

import json
import re

CAT = "ParametricStudio/Docs"

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_SAFE_PDF_EXTENSIONS = (".pdf",)

_DOC_STYLES = ("Concise", "Detailed", "Tutorial")

_LLM_MODELS = ("gpt-4", "llama3", "claude-3", "mistral")

# Heuristic: minimum number of non-empty text blocks for a "meaningful" doc.
_MIN_BLOCKS_FOR_CONFIDENCE = 3

# Maximum characters we will consider for the confidence heuristic.
_MAX_CONFIDENCE_CHARS = 200_000


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _is_safe_pdf_path(pdf_path):
    """Return (ok, reason). ok is True only if pdf_path looks like a safe PDF path."""
    if not isinstance(pdf_path, str):
        return False, "pdf_path must be a string"
    stripped = pdf_path.strip()
    if not stripped:
        return False, "pdf_path is empty"
    # Reject path traversal and absolute paths that escape a sandbox root.
    if ".." in stripped:
        return False, "pdf_path contains path traversal ('..')"
    if stripped.startswith("/") or stripped.startswith("\\"):
        return False, "pdf_path must be relative (no absolute paths)"
    # Check extension (case-insensitive).
    lower = stripped.lower()
    if not any(lower.endswith(ext) for ext in _SAFE_PDF_EXTENSIONS):
        return False, "pdf_path must end with a safe extension (.pdf)"
    return True, "ok"


def _split_text_blocks(raw_text):
    """Split raw text into blocks on blank-line boundaries. Returns list of str."""
    if not isinstance(raw_text, str):
        return []
    # Normalise line endings.
    normalised = raw_text.replace("\r\n", "\n").replace("\r", "\n")
    # Split on one or more blank lines.
    parts = re.split(r"\n\s*\n", normalised)
    blocks = [p.strip() for p in parts if p.strip()]
    return blocks


def _build_metadata_json(extract_metadata, pdf_path):
    """Build a JSON metadata string. Returns (json_str, error_str)."""
    if not extract_metadata:
        return "{}", ""
    meta = {
        "source": pdf_path,
        "format": "pdf",
        "extracted_by": "PSN_PDF_Structured_Extractor",
        "note": "Metadata is a placeholder; real extraction requires PyMuPDF.",
    }
    return json.dumps(meta, indent=2, sort_keys=True), ""


def _compute_confidence(blocks, doc_style):
    """Heuristic confidence score in [0, 1]."""
    if not blocks:
        return 0.0
    total_chars = sum(len(b) for b in blocks)
    if total_chars > _MAX_CONFIDENCE_CHARS:
        # Penalise very large inputs (context-window risk).
        base = 0.4
    elif total_chars > 50_000:
        base = 0.6
    else:
        base = 0.8

    # Reward having enough blocks.
    if len(blocks) >= _MIN_BLOCKS_FOR_CONFIDENCE:
        base = min(1.0, base + 0.1)
    else:
        base = max(0.0, base - 0.1)

    # Style adjustment: Detailed expects more content.
    if doc_style == "Detailed" and len(blocks) < _MIN_BLOCKS_FOR_CONFIDENCE:
        base = max(0.0, base - 0.1)

    return round(base, 4)


def _generate_markdown(blocks, doc_style, llm_model):
    """Build a deterministic Markdown document from text blocks."""
    lines = []
    lines.append("# Pipeline Documentation")
    lines.append("")
    lines.append(f"> Generated by PSN_LLM_Doc_Generator (model: {llm_model}, style: {doc_style})")
    lines.append("")

    if doc_style == "Tutorial":
        lines.append("## Tutorial Overview")
        lines.append("")
        lines.append("This document walks through the pipeline step by step.")
        lines.append("")

    if doc_style == "Concise":
        lines.append("## Summary")
        lines.append("")

    for idx, block in enumerate(blocks, start=1):
        if doc_style == "Concise":
            # First 200 chars only.
            snippet = block[:200]
            if len(block) > 200:
                snippet += "…"
            lines.append(f"### Section {idx}")
            lines.append("")
            lines.append(snippet)
            lines.append("")
        elif doc_style == "Tutorial":
            lines.append(f"### Step {idx}")
            lines.append("")
            lines.append(block)
            lines.append("")
        else:  # Detailed
            lines.append(f"### Section {idx}")
            lines.append("")
            lines.append(block)
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("*End of document.*")
    lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Node 1: PSN_PDF_Structured_Extractor
# ---------------------------------------------------------------------------

class PSN_PDF_Structured_Extractor:
    """Validate a PDF path and return structured text blocks + metadata JSON.

    Pure-logic: no file I/O. If `raw_text` is supplied (e.g. from a prior
    extraction step), it is split into blocks. Otherwise an empty structure
    is returned with a note that real extraction requires PyMuPDF.
    """

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "pdf_path": ("STRING", {"default": "sample_pipeline.pdf", "multiline": False}),
                "extract_images": ("BOOLEAN", {"default": False}),
                "extract_metadata": ("BOOLEAN", {"default": True}),
            },
            "optional": {
                "raw_text": ("STRING", {"default": "", "multiline": True}),
            },
        }

    RETURN_TYPES = ("STRING", "STRING", "STRING")
    RETURN_NAMES = ("text_content", "metadata", "status")
    FUNCTION = "run"
    CATEGORY = CAT

    def run(self, pdf_path, extract_images, extract_metadata, raw_text=""):
        ok, reason = _is_safe_pdf_path(pdf_path)
        if not ok:
            return ("", "{}", f"ERROR: {reason}")

        blocks = _split_text_blocks(raw_text)
        text_content = "\n\n".join(blocks)

        meta_json, meta_err = _build_metadata_json(extract_metadata, pdf_path)
        if meta_err:
            return (text_content, "{}", f"ERROR: {meta_err}")

        status_parts = [f"blocks={len(blocks)}"]
        if extract_images:
            status_parts.append("images=skipped (no PyMuPDF)")
        status = " | ".join(status_parts)

        return (text_content, meta_json, status)


# ---------------------------------------------------------------------------
# Node 2: PSN_LLM_Doc_Generator
# ---------------------------------------------------------------------------

class PSN_LLM_Doc_Generator:
    """Generate a deterministic Markdown document from extracted text blocks.

    Pure-logic: no LLM call, no network. The 'generation' is a local
    formatting step that produces valid Markdown. A heuristic confidence
    score is computed from block count and total character count.
    """

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "raw_text": ("STRING", {"default": "", "multiline": True}),
                "llm_model": (list(_LLM_MODELS),),
                "doc_style": (list(_DOC_STYLES),),
            },
            "optional": {
                "images": ("STRING", {"default": "", "multiline": False}),
            },
        }

    RETURN_TYPES = ("STRING", "FLOAT")
    RETURN_NAMES = ("markdown_doc", "confidence_score")
    FUNCTION = "run"
    CATEGORY = CAT

    def run(self, raw_text, llm_model, doc_style, images=""):
        blocks = _split_text_blocks(raw_text)
        confidence = _compute_confidence(blocks, doc_style)
        markdown = _generate_markdown(blocks, doc_style, llm_model)
        return (markdown, confidence)


